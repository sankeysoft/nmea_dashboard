import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:analyzer/dart/ast/ast.dart';
import 'package:analyzer/dart/ast/visitor.dart';
import 'package:build/build.dart';
import 'package:glob/glob.dart';

/// The directory containing the NMEA 0183 sentence parsers, relative to the package root.
const String nmea0183Dir = 'lib/state/parsing/0183';

/// The directory containing the NMEA 2000 PGN parsers, relative to the package root.
const String nmea2000Dir = 'lib/state/parsing/2000';

/// The generated file, relative to the package root.
const String outputPath = 'lib/state/parsing/property_sets.g.dart';

Builder propertySupportBuilder(BuilderOptions options) => PropertySupportBuilder();

/// Scans the parser source for each NMEA protocol and generates the set of Property values
/// referenced by any parser in that protocol.
class PropertySupportBuilder implements Builder {
  @override
  final buildExtensions = const {
    r'$lib$': ['state/parsing/property_sets.g.dart'],
  };

  @override
  Future<void> build(BuildStep buildStep) async {
    final package = buildStep.inputId.package;
    Future<List<String>> readAll(String dir) async {
      final ids = await buildStep.findAssets(Glob('$dir/*.dart')).toList();
      ids.sort((a, b) => a.path.compareTo(b.path));
      return Future.wait(ids.map(buildStep.readAsString));
    }

    final output = generatePropertySets(
      nmea0183Sources: await readAll(nmea0183Dir),
      nmea2000Sources: await readAll(nmea2000Dir),
    );
    await buildStep.writeAsString(AssetId(package, outputPath), output);
  }
}

/// Returns the contents of the generated file given the source of each parser file.
String generatePropertySets({
  required Iterable<String> nmea0183Sources,
  required Iterable<String> nmea2000Sources,
}) {
  final buffer = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('// Generated by tool/property_support_builder, run `dart run build_runner build`.')
    ..writeln()
    ..writeln("part of 'property_support.dart';")
    ..writeln();
  _writeSet(buffer, '_nmea0183Properties', _referencedProperties(nmea0183Sources));
  buffer.writeln();
  _writeSet(buffer, '_nmea2000Properties', _referencedProperties(nmea2000Sources));
  return buffer.toString();
}

void _writeSet(StringBuffer buffer, String name, Set<String> properties) {
  buffer.writeln('const Set<Property> $name = {');
  for (final property in properties.toList()..sort()) {
    buffer.writeln('  Property.$property,');
  }
  buffer.writeln('};');
}

/// Returns the names of all Property enum values referenced in the supplied sources.
Set<String> _referencedProperties(Iterable<String> sources) {
  final visitor = _PropertyVisitor();
  for (final source in sources) {
    parseString(content: source).unit.accept(visitor);
  }
  return visitor.properties;
}

class _PropertyVisitor extends RecursiveAstVisitor<void> {
  final properties = <String>{};

  @override
  void visitPrefixedIdentifier(PrefixedIdentifier node) {
    if (node.prefix.name == 'Property') {
      properties.add(node.identifier.name);
    }
    super.visitPrefixedIdentifier(node);
  }
}
